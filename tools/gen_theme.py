#!/usr/bin/env python3
"""Regenerate crates/surf-ui/src/theme.rs from docs/design/tokens.json.

    python3 tools/gen_theme.py && cargo fmt -p surf-ui
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((ROOT / "docs/design/tokens.json").read_text())


def hx(v):
    v = v.strip()
    if v.startswith("#"):
        return "rgb(0x%s)" % v[1:].lower()
    r, g, b, a = re.match(r"rgba\((\d+),(\d+),(\d+),([\d.]+)\)", v.replace(" ", "")).groups()
    return "rgba(0x%02x%02x%02x%02x)" % (int(r), int(g), int(b), round(float(a) * 255))


def const(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def px(v):
    return float(str(v).replace("px", ""))


c = t["color"]
out = []


def group(title, d, prefix="", rename=None):
    out.append(f"\n    // {title}")
    for k, v in d.items():
        if k.startswith("$") or not isinstance(v, dict) or "$value" not in v:
            continue
        name = (rename or {}).get(k, f"{prefix}{const(k)}")
        if v.get("$description"):
            out.append(f"    /// {v['$description']}")
        out.append(f"    pub const {name}: Rgba = {hx(v['$value'])};")


group("Surfaces", c["surface"])
group("Lines", c["line"], "LINE_", {"default": "LINE"})
group("Text", c["text"], "TEXT_")
group("Accent", c["accent"], "ACCENT_")
group("State", c["state"])
group("Grid", c["grid"], "GRID_")
group("Keyboard", c["keys"], "KEY_")
slots = [
    f"    pub const SLOT_{const(k)}: SlotColors = SlotColors {{ fg: {hx(v['fg']['$value'])}, bg: {hx(v['bg']['$value'])}, line: {hx(v['line']['$value'])} }};"
    for k, v in c["slot"].items()
    if not k.startswith("$") and "fg" in v
]
tracks = [hx(v["$value"]) for k, v in c["track"].items() if not k.startswith("$")]
vel = [hx(x) for x in c["velocity"]["stops"]["$value"]]
L = t["layout"]
layout = [
    ("CONTROL_BAR_H", L["controlBar"]["height"]), ("TOOLBAR_H", L["toolbar"]["height"]),
    ("PANE_HEADER_H", L["paneHeader"]["height"]), ("STATUS_BAR_H", L["statusBar"]["height"]),
    ("ICON_BUTTON", L["iconButton"]["size"]), ("ICON", L["iconButton"]["icon"]), ("LCD_H", L["lcd"]["height"]),
    ("LIBRARY_W", L["library"]["width"]), ("INSPECTOR_W", L["inspector"]["width"]),
    ("INSPECTOR_SECTION_H", L["inspector"]["sectionHeader"]), ("INSPECTOR_LABEL_W", L["inspector"]["labelColumn"]),
    ("TRACK_HEADER_W", L["trackHeader"]["width"]), ("LANE_H", L["lane"]["height"]),
    ("RULER_TRACKS_H", L["ruler"]["tracks"]), ("RULER_EDITOR_H", L["ruler"]["editor"]), ("SPLITTER", L["splitter"]["size"]),
    ("EDITOR_H", L["editor"]["defaultHeight"]), ("EDITOR_MIN_H", L["editor"]["minHeight"]),
    ("EDITOR_TABS_H", L["editor"]["tabs"]), ("EDITOR_BAR_H", L["editor"]["bar"]),
    ("LOCAL_INSPECTOR_W", L["editor"]["localInspector"]), ("ROLL_KEYS_W", L["pianoRoll"]["keysWidth"]),
    ("ROLL_ROW_H", L["pianoRoll"]["rowHeight"]), ("ROLL_VELOCITY_H", L["pianoRoll"]["velocityLane"]),
    ("ROLL_BEAT_W", L["pianoRoll"]["beatWidth"]["default"]), ("ROLL_BEAT_W_MIN", L["pianoRoll"]["beatWidth"]["min"]),
    ("ROLL_BEAT_W_MAX", L["pianoRoll"]["beatWidth"]["max"]), ("TRACKS_BEAT_W", L["tracksArea"]["beatWidth"]["default"]),
    ("TRACKS_BEAT_W_MIN", L["tracksArea"]["beatWidth"]["min"]), ("TRACKS_BEAT_W_MAX", L["tracksArea"]["beatWidth"]["max"]),
    ("STRIP_W", L["channelStrip"]["width"]), ("STRIP_SLOT_H", L["channelStrip"]["slot"]),
    ("STRIP_KNOB", L["channelStrip"]["knob"]), ("STRIP_METER_W", L["channelStrip"]["meter"]),
    ("STRIP_NAME_H", L["channelStrip"]["nameBar"]), ("MSR_W", L["msrButton"]["width"]), ("MSR_H", L["msrButton"]["height"]),
]
r = t["radius"]
f = t["font"]["size"]
nl = "\n"
src = f'''//! Design tokens for Surf's interface.
//!
//! **Generated from `docs/design/tokens.json` by `tools/gen_theme.py`.** Edit
//! the JSON and rerun the script; do not edit this file by hand. Views take
//! every color, size and font from here; no view should contain a color literal.

use gpui::Rgba;

/// `const` versions of `gpui::rgb` / `gpui::rgba`, so tokens can be constants.
pub const fn rgb(hex: u32) -> Rgba {{
    rgba((hex << 8) | 0xff)
}}

pub const fn rgba(hex: u32) -> Rgba {{
    Rgba {{
        r: ((hex >> 24) & 0xff) as f32 / 255.0,
        g: ((hex >> 16) & 0xff) as f32 / 255.0,
        b: ((hex >> 8) & 0xff) as f32 / 255.0,
        a: (hex & 0xff) as f32 / 255.0,
    }}
}}

/// Foreground, background and border of an instrument or effect slot.
#[derive(Clone, Copy)]
pub struct SlotColors {{
    pub fg: Rgba,
    pub bg: Rgba,
    pub line: Rgba,
}}

pub mod color {{
    use super::*;
{nl.join(out)}

    // Slots
{nl.join(slots)}

    /// Track colors, assigned round-robin to new tracks.
    pub const TRACKS: [Rgba; {len(tracks)}] = [{", ".join(tracks)}];

    /// Piano-roll note color by velocity, interpolated over 1..=127.
    pub const VELOCITY: [Rgba; {len(vel)}] = [{", ".join(vel)}];
}}

/// Font families. The files are bundled (see [`crate::fonts`]), so these
/// names always resolve.
pub mod font {{
    pub const UI: &str = "IBM Plex Sans";
    pub const LABEL: &str = "Barlow Condensed";
    pub const MONO: &str = "IBM Plex Mono";

    pub const CAPTION: f32 = {px(f["caption"]["$value"])};
    pub const LABEL_SIZE: f32 = {px(f["label"]["$value"])};
    pub const SMALL: f32 = {px(f["small"]["$value"])};
    pub const BODY: f32 = {px(f["body"]["$value"])};
    pub const TITLE: f32 = {px(f["title"]["$value"])};
    pub const LCD: f32 = {px(f["lcd"]["$value"])};
    pub const LCD_SMALL: f32 = {px(f["lcdSmall"]["$value"])};

    /// Letter spacing for uppercase labels, in em.
    pub const LABEL_TRACKING: f32 = {float(t["font"]["letterSpacing"]["label"].replace("em", ""))};
}}

pub mod radius {{
    pub const XS: f32 = {px(r["xs"]["$value"])};
    pub const SM: f32 = {px(r["sm"]["$value"])};
    pub const MD: f32 = {px(r["md"]["$value"])};
    pub const LG: f32 = {px(r["lg"]["$value"])};
}}

/// Fixed sizes from the layout spec, in logical pixels.
pub mod size {{
{nl.join(f"    pub const {n}: f32 = {px(v)};" for n, v in layout)}
}}
'''
(ROOT / "crates/surf-ui/src/theme.rs").write_text(src)
print("wrote crates/surf-ui/src/theme.rs")
